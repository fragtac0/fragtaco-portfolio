// Writes app/styles/fonts-interface.css and app/styles/fonts-spine.css from the Fontsource packages (OFL-1.1, the same open-licensed
// files Google Fonts serves). Re-run after changing a package or the list below:  node scripts/fonts/build-font-css.mjs
// Why a script and not the packages' own stylesheets: the variable packages name their family "Archivo Variable", "Doto Variable" ...,
// and the site (its CSS and the book spines' canvas code) asks for "Archivo", "Doto" ...; the names are kept as the site uses them.
// `--check` writes nothing and exits 1 when a committed file differs from what this script makes (app/styles/fonts-generated.test.ts runs it).
// Each block keeps the package's unicode-range (so a visitor downloads only the subsets the text needs), takes the weight (and width)
// range the two Google stylesheets asked for, keeps `font-display: swap`, and points at the woff2 file only.
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const NM = "node_modules";
// [package, family the site uses, [stylesheets of the package], font-weight descriptor (null: the package's own), font-stretch descriptor]
const INTERFACE = [
  ["@fontsource-variable/doto", "Doto", ["wght.css"], "400 900"],
  ["@fontsource/ibm-plex-mono", "IBM Plex Mono", ["400.css", "500.css", "600.css"]],
  ["@fontsource-variable/lora", "Lora", ["wght.css"], "500 700"],
  ["@fontsource/space-mono", "Space Mono", ["400.css", "700.css", "400-italic.css"]],
  ["@fontsource-variable/tektur", "Tektur", ["wght.css"], "500 800"],
];
const SPINE = [
  ["@fontsource-variable/archivo", "Archivo", ["wdth.css", "wdth-italic.css"], "100 900", "62% 125%"],
  ["@fontsource-variable/bodoni-moda", "Bodoni Moda", ["opsz.css", "opsz-italic.css"], "400 900"],
  ["@fontsource-variable/newsreader", "Newsreader", ["opsz.css", "opsz-italic.css"], "300 800"],
  ["@fontsource-variable/space-grotesk", "Space Grotesk", ["wght.css"], "300 700"],
  ["@fontsource-variable/unbounded", "Unbounded", ["wght.css"], "300 900"],
  ["@fontsource/young-serif", "Young Serif", ["400.css"]],
];

function blocks(list) {
  const out = [];
  for (const [pkg, family, sheets, weight, stretch] of list) {
    const version = JSON.parse(readFileSync(`${NM}/${pkg}/package.json`, "utf8")).version;
    out.push(`/* ${family}: ${pkg}@${version}, ${sheets.join(" ")} */`);
    for (const sheet of sheets) {
      const css = readFileSync(`${NM}/${pkg}/${sheet}`, "utf8");
      for (const m of css.matchAll(/\/\*\s*([^*]+?)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)) {
        const body = m[2];
        const get = (p) => new RegExp(`${p}:\\s*([^;]+);`).exec(body)?.[1].trim();
        const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(body)?.[1];
        if (!file) throw new Error(`no woff2 in ${pkg}/${sheet} (${m[1]})`);
        const parts = [
          `font-family:"${family}"`,
          `font-style:${get("font-style")}`,
          `font-weight:${weight ?? get("font-weight")}`,
          ...(stretch ? [`font-stretch:${stretch}`] : []),
          "font-display:swap",
          `src:url("../../${NM}/${pkg}/files/${file}") format("woff2")`,
          `unicode-range:${get("unicode-range")}`,
        ];
        out.push(`/* ${m[1]} */`, `@font-face{${parts.join(";")}}`);
      }
    }
  }
  return out.join("\n") + "\n";
}

const head = (what) =>
  `/* Generated by scripts/fonts/build-font-css.mjs from the Fontsource packages (OFL-1.1): ${what}. Do not edit by hand. */\n`;
// The OFL asks that the licence and copyright notices travel with the font files: one text, served from the site's own origin.
const licences = [...INTERFACE, ...SPINE]
  .map(([pkg, family]) => `${"=".repeat(78)}\n${family} (${pkg}, SIL Open Font License 1.1)\n${"=".repeat(78)}\n\n${readFileSync(`${NM}/${pkg}/LICENSE`, "utf8").trim()}\n`)
  .join("\n");
const files = {
  "public/font-licences.txt": `The typefaces of this site are free software under the SIL Open Font License 1.1, from the Fontsource packages of the Google Fonts families.\n\n${licences}`,
  "app/styles/fonts-interface.css": head("the interface faces") + blocks(INTERFACE),
  "app/styles/fonts-spine.css": head("the book-spine faces (art, not interface)") + blocks(SPINE),
};
if (process.argv.includes("--check")) {
  const stale = Object.entries(files).filter(([path, text]) => !existsSync(path) || readFileSync(path, "utf8") !== text).map(([path]) => path);
  if (stale.length) {
    console.error(`out of step with the generator (run: yarn fonts): ${stale.join(", ")}`);
    process.exit(1);
  }
  console.log("the generated font files match the generator");
} else {
  for (const [path, text] of Object.entries(files)) writeFileSync(path, text);
}
